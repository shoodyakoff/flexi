"""Слой уникализации: как один ролик садится в кадр и в громкость.

Общий движок для всех потоков, которые публикуют много роликов из общих кусков
(«Весёлые», «Умный отклик», «Анализ резюме»). Смысл — не «обмануть хэш», а дать
каждому файлу свою геометрию: Instagram сравнивает опубликованное с
опубликованным, поэтому разводить надо **пары вариантов**, а не вариант с
оригиналом (замер: пара сидов со старой фиксированной рамкой = 45 бит медианы
при минимуме 30 — ниже порога Меты 31).

Рычаги, по измеренной силе на кадровом хэше (`ДЕДУП_ИТОГИ_И_ДОРАБОТКИ.md` §2):

* **наклон** ≤1° — 0.7° даёт ≈70 бит из 256;
* **своя рамка кадра** (кроп ±2% + дрейф за время ролика) — ≈46 бит, и, в
  отличие от наклона, каждый следующий секундный кадр сдвинут иначе, чем
  предыдущий — а сравнивается именно посекундная выборка;
* **микро-темп** ±1.5% — меняет длительность и ломает сигнатуры целого ролика;
* зерно, hue, перекодирование, метаданные — измерены как ≈0, не используются.

Кадр никогда не зеркалится (порушит прожжённый текст), высота звука не меняется.
Ни одна комбинация параметров не может открыть чёрный угол: запас кадра
считается под конкретный наклон и дрейф (``overscale_for``).
"""

